/// 二级界面「点开才出现」的文案预翻译清单。
///
/// ## 为什么需要这个
///
/// App 里大量文案**只在用户点开弹窗/菜单时才渲染**：缓存视频右侧 ⋮ 的菜单、
/// 删除确认框、排序方式选择、多选框……这些文字在页面刚打开时从未出现在控件树里，
/// 也就从未调用过 `uiTx()`，自然没进过翻译队列。
///
/// 结果是：用户点开 ⋮，先看到一串中文，过一两秒才跳成日语——体验很突兀。
///
/// ## 做法
///
/// 进入二级界面时，把该界面**所有可能被触发的**文案一次性交给
/// [UiTranslateService.precacheLater]，让它们走优先队列预热。用户真正点开时，
/// 译文已经在缓存里，`uiTx()` 同步命中，直接显示译文。
///
/// ## 维护约定
///
/// **在本文件按「界面」分组维护**。新增任何弹窗/菜单/确认框时，
/// 把它的文案加进对应分组。宁可多列几条（未命中只是多一次翻译请求），
