/// 应用/翻译目标语言模型。
///
/// [name] 用该语言的“自称/原语写法”显示在界面上（如 English、日本語、繁體粵語）；
/// [toModel] 是发给翻译模型的提示词（含书写系统、地区用字规范等“只让 AI 知道、
/// 不显示给用户”的说明）；[chineseFamily] 标记该语言属于中文家族（简繁、粤、吴、
/// 闽南等），仅用于分组/展示。
///
/// **注意**：是否跳过翻译只看 `UiTranslateService.isSourceLanguage`，也就是
/// **只有简体中文**（B 站原文语言）跳过；繁体中文、粤语、吴语、闽南语虽然
/// chineseFamily 也是 true，但它们不是原文，仍然要调用 API 翻译。
class AppLanguage {
  const AppLanguage(
    this.code,
    this.name,
    this.toModel, {
    this.chineseFamily = false,
    this.script,
    this.nativeScript,
  });

  final String code;
  final String name;
  final String toModel;
  final bool chineseFamily;

  /// 字形规范：`'Hans'`（简体）/ `'Hant'`（繁體）/ `null`（非中文家族，不限字形）。
  ///
  /// 只管「字形」，不管方言——粤语 / 吴语 / 闽南语各自都有 Hans 与 Hant 两档。
  final String? script;

  /// 该语言的「专属文字」标识（见 [looksLikeNativeScript]）。
  ///
  /// 用来判断一段文本**本来就用目标语言书写**，从而跳过翻译。只给
  /// 文字与语言一一对应的语言配；拉丁 / 西里尔 / 阿拉伯字母被多个语言共用，
  /// 一律不配。
  final String? nativeScript;

  /// 追加到系统提示词里的**字形硬约束**，用目标字形本身书写。
  ///
  /// 为什么要单独写一段：系统提示词通篇是简体，翻繁體目标时会把模型带偏，
  /// 输出里就夹杂简体字（反之亦然）。用目标字形把约束再说一遍，并给出高频
  /// 易错字的对照表——模型对「具体字符」的约束比对「请用繁体」敏感得多。
  String get scriptRule => switch (script) {
    'Hans' => hansScriptRule,
    'Hant' => hantScriptRule,
    _ => '',
  };
}

