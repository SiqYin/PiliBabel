  if (text.isEmpty) return text;
  final Map<String, String>? table = switch (script) {
    'Hans' => _hantToHans,
    'Hant' => _hansToHant,
    _ => null,
  };
  if (table == null) return text;
  final buffer = StringBuffer();
  for (final rune in text.runes) {
    final char = String.fromCharCode(rune);
    buffer.write(table[char] ?? char);
  }
  return buffer.toString();
}

/// 判断文本是否**本来就用目标语言书写**（据此跳过翻译）。
///
/// 只收录「文字 ↔ 语言一一对应」的：日文假名、韩文谚文、泰文、藏文、希伯来文。
/// 拉丁字母 / 西里尔字母 / 阿拉伯字母被多个语言共用（英法德西、俄乌蒙、
/// 阿拉伯与维吾尔），一概不收——否则会把「法语标题」误判成「已经是英语」
/// 而不翻，那是实打实的回归。
///
/// 典型场景：日语界面里，一个本来就是日语的视频标题（含假名）不需要翻译，
/// 原样显示即可，既省 token，也避免模型把专有名词译歪。
bool looksLikeNativeScript(String text, String? nativeScript) {
  if (text.isEmpty || nativeScript == null) return false;
  for (final rune in text.runes) {
    final matched = switch (nativeScript) {
      // 平假名 + 片假名 + 半角片假名
      'kana' =>
        (rune >= 0x3040 && rune <= 0x30FF) ||
            (rune >= 0xFF66 && rune <= 0xFF9D),
      // 谚文音节 + 字母 + 兼容字母
      'hangul' =>
        (rune >= 0xAC00 && rune <= 0xD7AF) ||
            (rune >= 0x1100 && rune <= 0x11FF) ||
            (rune >= 0x3130 && rune <= 0x318F),
      'thai' => rune >= 0x0E00 && rune <= 0x0E7F,
      'tibetan' => rune >= 0x0F00 && rune <= 0x0FFF,
      'hebrew' => rune >= 0x0590 && rune <= 0x05FF,
      _ => false,
    };
    if (matched) return true;
  }
  return false;
}

